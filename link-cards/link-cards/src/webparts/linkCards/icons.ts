export const ICON_NAMES: string[] = Object.keys(ICONS).sort();

/** Human-readable name for the picker: "ClipboardCheck" -> "Clipboard check". */
export function iconLabel(name: string): string {
  const spaced = name.replace(/([a-z])([A-Z0-9])/g, '$1 $2').replace(/([0-9])([A-Z])/g, '$1 $2');
  return spaced.charAt(0) + spaced.slice(1).toLowerCase();
}

export function getIcon(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || FileText;
}
